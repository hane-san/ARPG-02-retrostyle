export function applyFixedPeople(room){
 for(const [id,name,a,b,x,y] of FIXED_PEOPLE){
  if(id!==room.id)continue;
  if(x===undefined){if(!room.npcs[0])throw Error(id+': missing original resident');Object.assign(room.npcs[0],{name,lines:[a,b]});continue;}
  const clear=(x,y)=>{
   if(!['g','='].includes(room.tileAt(x,y))||room.npcs.some(n=>Math.hypot(n.x-x,n.y-y)<3)||room.trees.some(([a,b])=>Math.hypot(a-x,b-y)<1.5))return false;
   if([room.returnStone,...[room.site,...room.props].filter(Boolean).map(s=>s.entrance)].filter(Boolean).some(p=>Math.hypot(p.x-x,p.y-y)<1.5))return false;
   if([room.site,...room.props,room.house].filter(s=>s&&!(['wet-temple','dry-temple'].includes(room.id)&&s===room.site)).some(s=>x>=s.x&&x<s.x+s.w&&y>=s.y&&y<s.y+s.h))return false;
   if(Object.entries(room.seams).some(([d,s])=>s.bands.some(([lo,hi])=>Math.hypot(x-(d==='W'?2:d==='E'?12:(lo+hi)/2),y-(d==='N'?2:d==='S'?12:(lo+hi)/2))<1.5)))return false;
   if(room.features.some(f=>(f.cells||[[f.x,f.y]]).some(([a,b])=>Math.hypot(a-x,b-y)<1.5)))return false;
   return [[1,0],[-1,0],[0,1],[0,-1]].filter(([dx,dy])=>room.walkable(x+dx,y+dy)).length>=3;
  };
  const points=[];for(let yy=2;yy<=12;yy++)for(let xx=2;xx<=12;xx++)if(clear(xx,yy))points.push({x:xx,y:yy});
  points.sort((a,b)=>(room.tileAt(a.x,a.y)==='g'?0:100)-(room.tileAt(b.x,b.y)==='g'?0:100)+Math.hypot(a.x-x,a.y-y)-Math.hypot(b.x-x,b.y-y)||a.y-b.y||a.x-b.x);
  if(!points.length)throw Error(id+': no safe resident clearing');
  room.npcs.push({...points[0],name,lines:[a,b],color:'#9a8067'});
 }
}
